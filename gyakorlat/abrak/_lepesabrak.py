FEJ = r"""\documentclass[tikz,border=6pt]{standalone}
\usepackage{peabra}
\begin{document}
\begin{tikzpicture}[x=1cm,y=1cm,
  lep/.style={draw=peKek, fill=peHalvany, rounded corners=2pt, line width=0.8pt, align=center,
    font=\footnotesize, text width=30mm, minimum height=13mm, inner sep=3pt},
  szam/.style={circle, fill=peKiemel, text=white, font=\scriptsize\bfseries, inner sep=0, minimum size=5mm}]
"""


def abra(nev, lepesek, vissza):
    s = [FEJ]
    dx, dy = 3.9, 2.2
    for i, t in enumerate(lepesek):
        sor, osz = divmod(i, 4)
        s.append(rf"  \node[lep] (l{i+1}) at ({osz*dx:.2f},{-sor*dy:.2f}) {{{t}}};")
        s.append(rf"  \node[szam] at (l{i+1}.north west) {{{i+1}}};")
    for i in range(1, len(lepesek)):
        if i % 4 == 0:
            s.append(rf"  \draw[nyil, line width=0.7pt] (l{i}.south) -- ++(0,-0.38) -| (l{i+1}.north);")
        else:
            s.append(rf"  \draw[nyil, line width=0.7pt] (l{i}.east) -- (l{i+1}.west);")
    if vissza:
        a, b, felirat = vissza
        s.append(rf"  \draw[-{{Stealth[length=2mm]}}, draw=pePiros, line width=0.7pt, dash pattern=on 3pt off 2pt]"
                 rf" ($(l{a}.north)+(-0.55,0)$) to[bend left=18] node[midway, left=1pt, font=\scriptsize, text=pePiros, align=right] {{{felirat}}}"
                 rf" ($(l{b}.south)+(-0.55,0)$);")
    s.append(r"\end{tikzpicture}")
    s.append(r"\end{document}")
    _f = CEL / f"lepesek-{nev}.tex"
    _uj = "\n".join(s) + "\n"
    if not _f.exists() or _f.read_text(encoding="utf-8") != _uj:   # csak változáskor írjuk (ne forduljon újra minden ábra)
        _f.write_text(_uj, encoding="utf-8")


if __name__ == "__main__":
    CEL.mkdir(parents=True, exist_ok=True)
    for nev, (lepesek, vissza) in ABRAK.items():
        abra(nev, lepesek, vissza)
    print("kész:", ", ".join(ABRAK))
